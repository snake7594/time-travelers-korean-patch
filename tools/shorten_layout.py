def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    rows = []
    seen = set()
    for raw in MAP.read_text(encoding="utf-8").splitlines():
        row = json.loads(raw)
        key = row["id"]
        if key in REPLACEMENTS:
            row["ko"] = REPLACEMENTS[key]
            seen.add(key)
        rows.append(row)
    missing = set(REPLACEMENTS) - seen
    if missing:
        raise SystemExit(f"replacement ids not found: {sorted(missing)}")
    bad = []
    for key, text in REPLACEMENTS.items():
        lens = [len(TAG.sub("", part)) for part in text.split(MARK)]
        if len(lens) > 2 or max(lens, default=0) > LIMIT:
            bad.append((key, lens, text))
    if bad:
        for item in bad:
            print(item)
        raise SystemExit(f"{len(bad)} replacement(s) still exceed layout budget")
    MAP.write_text("\n".join(json.dumps(r, ensure_ascii=False, separators=(",", ":")) for r in rows) + "\n", encoding="utf-8")
    print(f"updated {len(seen)} compact layout translations")


if __name__ == "__main__":
    main()
